"""ChromaDB vector store — persistent local vector database for document embeddings.

Provides:
- Persistent ChromaDB collection for document chunks
- Upsert / delete operations for ingestion
- Semantic similarity search for retrieval
- Metadata filtering (document_id, page_number, section)
"""

from __future__ import annotations
import logging
import os
from typing import List, Optional
from dataclasses import dataclass, field

import chromadb
from chromadb.config import Settings as ChromaSettings

from config import get_settings
from embeddings.encoder import encoder

logger = logging.getLogger(__name__)
settings = get_settings()


class ChromaStore:
    """Singleton ChromaDB vector store manager.

    Uses persistent storage so the collection survives restarts.
    Embeddings are generated by our local SentenceTransformer encoder.
    """

    _instance: ChromaStore | None = None
    _client: chromadb.ClientAPI | None = None
    _collection: chromadb.Collection | None = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def _ensure_client(self):
        """Initialize ChromaDB persistent client and collection."""
        if self._client is None:
            persist_dir = os.path.abspath(settings.chroma_persist_dir)
            os.makedirs(persist_dir, exist_ok=True)

            self._client = chromadb.PersistentClient(
                path=persist_dir,
                settings=ChromaSettings(
                    anonymized_telemetry=False,
                    allow_reset=True,
                ),
            )
            logger.info("ChromaDB client initialized at: %s", persist_dir)

        if self._collection is None:
            self._collection = self._client.get_or_create_collection(
                name=settings.chroma_collection_name,
                metadata={"hnsw:space": "cosine"},  # cosine similarity
            )
            count = self._collection.count()
            logger.info(
                "ChromaDB collection '%s' ready — %d documents",
                settings.chroma_collection_name,
                count,
            )

    @property
    def collection(self) -> chromadb.Collection:
        self._ensure_client()
        return self._collection

    # ── Ingestion Operations ─────────────────────────────────────────────

    def upsert_chunks(
        self,
        chunk_ids: List[str],
        contents: List[str],
        embeddings: List[List[float]],
        metadatas: List[dict],
    ) -> int:
        """Upsert document chunks into ChromaDB.

        Args:
            chunk_ids: Unique IDs for each chunk.
            contents: Text content of each chunk.
            embeddings: Pre-computed embedding vectors.
            metadatas: Metadata dicts (document_id, document_name, page_number, etc.)

        Returns:
            Number of chunks upserted.
        """
        self._ensure_client()

        if not chunk_ids:
            return 0

        # ChromaDB has a batch size limit; process in batches
        batch_size = 500
        total = 0

        for i in range(0, len(chunk_ids), batch_size):
            batch_ids = chunk_ids[i : i + batch_size]
            batch_contents = contents[i : i + batch_size]
            batch_embeddings = embeddings[i : i + batch_size]
            batch_metadatas = metadatas[i : i + batch_size]

            # Sanitize metadata — ChromaDB only allows str, int, float, bool
            sanitized_metas = []
            for meta in batch_metadatas:
                sanitized = {}
                for k, v in meta.items():
                    if v is None:
                        sanitized[k] = ""
                    elif isinstance(v, (str, int, float, bool)):
                        sanitized[k] = v
                    elif isinstance(v, list):
                        sanitized[k] = str(v)
                    else:
                        sanitized[k] = str(v)
                sanitized_metas.append(sanitized)

            self._collection.upsert(
                ids=batch_ids,
                documents=batch_contents,
                embeddings=batch_embeddings,
                metadatas=sanitized_metas,
            )
            total += len(batch_ids)

        logger.info("Upserted %d chunks into ChromaDB", total)
        return total

    def delete_by_document(self, document_id: str) -> None:
        """Delete all chunks belonging to a document."""
        self._ensure_client()
        self._collection.delete(
            where={"document_id": document_id},
        )
        logger.info("Deleted chunks for document %s from ChromaDB", document_id)

    # ── Search Operations ────────────────────────────────────────────────

    def semantic_search(
        self,
        query: str,
        top_k: int = 20,
        document_ids: List[str] | None = None,
    ) -> List[dict]:
        """Perform semantic similarity search using ChromaDB.

        Args:
            query: The search query.
            top_k: Number of results to return.
            document_ids: Optional filter by document IDs.

        Returns:
            List of result dicts with chunk_id, content, metadata, similarity.
        """
        self._ensure_client()

        query_embedding = encoder.encode_query(query)

        # Build where filter
        where_filter = None
        if document_ids:
            if len(document_ids) == 1:
                where_filter = {"document_id": document_ids[0]}
            else:
                where_filter = {"document_id": {"$in": document_ids}}

        try:
            results = self._collection.query(
                query_embeddings=[query_embedding],
                n_results=min(top_k, self._collection.count() or 1),
                where=where_filter if where_filter else None,
                include=["documents", "metadatas", "distances"],
            )
        except Exception as e:
            logger.error("ChromaDB search failed: %s", e)
            return []

        # Parse results
        chunks = []
        if results and results["ids"] and results["ids"][0]:
            ids = results["ids"][0]
            documents = results["documents"][0] if results["documents"] else [""] * len(ids)
            metadatas = results["metadatas"][0] if results["metadatas"] else [{}] * len(ids)
            distances = results["distances"][0] if results["distances"] else [1.0] * len(ids)

            for chunk_id, content, metadata, distance in zip(ids, documents, metadatas, distances):
                # ChromaDB cosine distance: 0 = identical, 2 = opposite
                # Convert to similarity: 1 - (distance / 2)
                similarity = 1.0 - (distance / 2.0)

                chunks.append({
                    "chunk_id": chunk_id,
                    "content": content,
                    "metadata": metadata,
                    "similarity": similarity,
                    "document_id": metadata.get("document_id", ""),
                    "document_name": metadata.get("document_name", ""),
                    "page_number": metadata.get("page_number"),
                    "section": metadata.get("section", ""),
                    "content_type": metadata.get("content_type", "paragraph"),
                    "heading_hierarchy": metadata.get("heading_hierarchy", "[]"),
                })

        return chunks

    @property
    def count(self) -> int:
        """Get the number of documents in the collection."""
        self._ensure_client()
        return self._collection.count()

    def reset(self):
        """Reset the collection (delete all data). Use with caution."""
        self._ensure_client()
        self._client.delete_collection(settings.chroma_collection_name)
        self._collection = None
        self._ensure_client()
        logger.warning("ChromaDB collection reset!")


# Module-level singleton
chroma_store = ChromaStore()
